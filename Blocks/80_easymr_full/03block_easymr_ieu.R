###############################################################################
#  easymr_ieu — 在 OpenGWAS / IEU 目录里查欧洲人研究，并按编号在线提取工具变量
#
#  register_block: "easymr_ieu"
#  典型位置: 还没有本地 GWAS 文件时。不插入发病/预后主链
#  目录来自本机 easyMR 包里的 ao 表，不需要 key
#  在线提取才需要 OpenGWAS JWT，从 jwt_file 读取，不写进脚本
#
#  config$easymr_ieu = list(
#    query = "albumin",          # 性状词；或直接写 ieu-b-110 这类编号
#    population = "European",
#    drop_eqtl = TRUE,
#    jwt_file = "E:/孟德尔/0代码/opengwas_jwt.txt",
#    extract_ids = NULL,        # 字符向量。空则只查目录，不访问 OpenGWAS
#    rscript = "C:/Program Files/R/R-4.2.2/bin/Rscript.exe",
#    save_dir = NULL,
#    p1 = 5e-8, clump = TRUE, r2 = 0.001, kb = 10000,
#    dry_run = FALSE
#  )
#
#  写出: gwas_ieu_<query>.csv / .md
#        若 extract_ids 非空：<id>_instruments.csv
#  ctx$results$easymr_ieu: csv, markdown, n_studies
###############################################################################

if (!exists("%||%", mode = "function")) {
  `%||%` <- function(x, y) if (is.null(x) || length(x) == 0) y else x
}

.ieu_slash <- function(p) gsub("\\\\", "/", p)

.ieu_to_host <- function(p) {
  p <- .ieu_slash(p)
  if (grepl("^[A-Za-z]:/", p)) {
    alt <- paste0("/mnt/", tolower(substr(p, 1, 1)), substring(p, 3))
    if (file.exists(alt) || file.exists(paste0(alt, ".rdx"))) return(alt)
  }
  p
}

.ieu_to_win <- function(p) {
  p <- .ieu_slash(p)
  if (grepl("^/mnt/[a-zA-Z]/", p)) {
    paste0(toupper(substr(p, 6, 6)), ":", substring(p, 7))
  } else {
    p
  }
}

.ieu_r_quote <- function(x) {
  x <- enc2utf8(as.character(x))
  cps <- utf8ToInt(x)
  parts <- vapply(cps, function(cp) {
    if (cp == 34L) return("\\\"")
    if (cp == 92L) return("\\\\")
    if (cp >= 32L && cp < 127L) return(intToUtf8(cp))
    sprintf("\\u%04x", cp)
  }, character(1))
  paste0("\"", paste(parts, collapse = ""), "\"")
}

.ieu_load_ao <- function(rdata) {
  path <- .ieu_to_host(rdata)
  if (!file.exists(paste0(path, ".rdx"))) {
    stop("找不到 easyMR 的 ao 数据: ", rdata)
  }
  e <- new.env(parent = emptyenv())
  lazyLoad(path, envir = e)
  if (is.null(e$ao)) stop("easyMR 数据包里没有 ao")
  e$ao
}

.ieu_slug <- function(x) {
  x <- tolower(gsub("[^A-Za-z0-9]+", "_", x))
  gsub("^_|_$", "", x)
}

.ieu_search_ao <- function(ao, query, population, drop_eqtl) {
  ao <- ao[!is.na(ao$population) & ao$population == population, , drop = FALSE]
  if (isTRUE(drop_eqtl)) {
    ao <- ao[!grepl("^eqtl-", ao$id), , drop = FALSE]
  }
  if (grepl("^[A-Za-z]+-[A-Za-z]+-", query)) {
    hit <- ao[ao$id == query | startsWith(ao$id, query), , drop = FALSE]
  } else {
    pat <- paste0("\\b", gsub("([.|()\\^{}+$*?\\[\\]])", "\\\\\\1", query), "\\b")
    hit <- ao[grepl(pat, ao$trait, ignore.case = TRUE), , drop = FALSE]
  }
  if (!nrow(hit)) return(hit)
  hit$sample_size_n <- suppressWarnings(as.numeric(gsub(",", "", as.character(hit$sample_size))))
  hit$year_n <- suppressWarnings(as.numeric(hit$year))
  hit <- hit[order(hit$year_n, hit$sample_size_n, decreasing = TRUE, na.last = TRUE), , drop = FALSE]
  keep <- c(
    "id", "trait", "year", "author", "consortium", "sex", "population",
    "sample_size", "ncase", "ncontrol", "unit", "nsnp", "pmid", "build",
    "category", "subcategory", "note"
  )
  keep <- keep[keep %in% names(hit)]
  hit[, keep, drop = FALSE]
}

.ieu_write_md <- function(path, query, studies) {
  lines <- c(
    paste0("# ", query, "：OpenGWAS 欧洲人研究"),
    "",
    paste0("检索日 ", format(Sys.Date()), "。来源是本机 easyMR 包里的 ao 表，人群限定为 European。这张表不访问网站，也不使用 JWT。"),
    "编号形如 ieu-b-110。在线提取工具变量时把编号放进 extract_ids，key 只放在 jwt_file 里。",
    "`get_opengwas_jwt()` 和 `user()` 只检查 key 是否有效，不会下载 GWAS。",
    "",
    paste0("共 ", nrow(studies), " 条，按年份、样本量从新到大。"),
    ""
  )
  if (!nrow(studies)) {
    lines <- c(lines, "没有符合条件的研究。")
  } else {
    show_n <- min(nrow(studies), 40L)
    for (i in seq_len(show_n)) {
      r <- studies[i, ]
      lines <- c(lines, paste0(
        "- ", r$id, " | ", r$year, " | N=", r$sample_size,
        " | ", r$trait, " | ", r$author, " | PMID ", r$pmid
      ))
    }
    if (nrow(studies) > show_n) {
      lines <- c(lines, "", paste0("其余 ", nrow(studies) - show_n, " 条见 csv。"))
    }
  }
  writeLines(lines, path, useBytes = TRUE)
}

.ieu_write_extract_runner <- function(path, cfg, ids) {
  id_bits <- paste(vapply(ids, .ieu_r_quote, ""), collapse = ", ")
  body <- c(
    "# Generated by block easymr_ieu. ASCII only. JWT is read from file.",
    "suppressPackageStartupMessages(library(ieugwasr))",
    "suppressPackageStartupMessages(library(TwoSampleMR))",
    sprintf("jwt_file <- %s", .ieu_r_quote(.ieu_to_win(cfg$jwt_file))),
    sprintf("save_dir <- %s", .ieu_r_quote(.ieu_to_win(cfg$save_dir))),
    "dir.create(save_dir, recursive = TRUE, showWarnings = FALSE)",
    "if (!file.exists(jwt_file)) stop(\"Missing JWT file: \", jwt_file)",
    "tok <- trimws(readLines(jwt_file, n = 1L, warn = FALSE, encoding = \"UTF-8\"))",
    "if (!nzchar(tok)) stop(\"JWT file is empty: \", jwt_file)",
    "Sys.setenv(OPENGWAS_JWT = tok)",
    "rm(tok)",
    "u <- try(user(), silent = TRUE)",
    "if (inherits(u, \"try-error\")) stop(\"OpenGWAS user() failed. Check the JWT file and its expiry.\")",
    "cat(\"IEU_USER_OK\", format(Sys.time()), \"\\n\")",
    sprintf("ids <- c(%s)", id_bits),
    sprintf("p1 <- %s", format(cfg$p1 %||% 5e-8, scientific = TRUE)),
    sprintf("clump <- %s", if (isFALSE(cfg$clump)) "FALSE" else "TRUE"),
    sprintf("r2 <- %s", cfg$r2 %||% 0.001),
    sprintf("kb <- %s", as.integer(cfg$kb %||% 10000L)),
    "for (id in ids) {",
    "  cat(\"START\", id, format(Sys.time()), \"\\n\")",
    "  exp <- try(TwoSampleMR::extract_instruments(outcomes = id, p1 = p1, clump = clump, p2 = p1, r2 = r2, kb = kb), silent = TRUE)",
    "  if (inherits(exp, \"try-error\") || is.null(exp) || !nrow(exp)) {",
    "    cat(\"FAIL\", id, if (inherits(exp, \"try-error\")) as.character(exp) else \"empty\", \"\\n\")",
    "    next",
    "  }",
    "  out <- file.path(save_dir, paste0(id, \"_instruments.csv\"))",
    "  utils::write.csv(exp, out, row.names = FALSE)",
    "  cat(\"WROTE\", id, nrow(exp), out, \"\\n\")",
    "}"
  )
  writeLines(body, path, useBytes = TRUE)
  invisible(path)
}

block_easymr_ieu <- function(ctx, ...) {
  cfg <- (ctx$config$easymr_ieu) %||% list()
  query <- cfg$query %||% ""
  ids <- cfg$extract_ids %||% character()
  if (!nzchar(query) && !length(ids)) stop("config$easymr_ieu$query 为空")
  save_dir <- cfg$save_dir %||% ctx$output_dir %||% file.path(tempdir(), "easymr_ieu")
  dir.create(save_dir, recursive = TRUE, showWarnings = FALSE)
  cfg$save_dir <- save_dir
  rdata <- cfg$ao_rdata %||% "C:/Program Files/R/R-4.2.2/library/easyMR/data/Rdata"
  studies <- data.frame()
  if (nzchar(query)) {
    ao <- .ieu_load_ao(rdata)
    studies <- .ieu_search_ao(
      ao, query,
      population = cfg$population %||% "European",
      drop_eqtl = cfg$drop_eqtl %||% TRUE
    )
    slug <- .ieu_slug(query)
    csv <- file.path(save_dir, paste0("gwas_ieu_", slug, ".csv"))
    md <- file.path(save_dir, paste0("gwas_ieu_", slug, ".md"))
    utils::write.csv(studies, csv, row.names = FALSE, fileEncoding = "UTF-8")
    .ieu_write_md(md, query, studies)
    message("IEU 目录写出 ", csv, " （", nrow(studies), " 条）")
  } else {
    csv <- NA_character_
    md <- NA_character_
  }
  ctx$results$easymr_ieu <- list(
    studies_csv = csv,
    markdown = md,
    n_studies = nrow(studies),
    extract_ids = ids
  )
  if (!length(ids)) return(ctx)
  cfg$jwt_file <- cfg$jwt_file %||% "E:/孟德尔/0代码/opengwas_jwt.txt"
  runner <- file.path(save_dir, "easymr_ieu_extract.R")
  .ieu_write_extract_runner(runner, cfg, ids)
  ctx$results$easymr_ieu$runner <- runner
  if (isTRUE(cfg$dry_run)) {
    message("easymr_ieu dry_run: wrote ", runner)
    return(ctx)
  }
  if (!file.exists(.ieu_to_host(cfg$jwt_file))) {
    stop("找不到 JWT 文件: ", cfg$jwt_file, "。把 key 单独存成一行，不要写进 block。")
  }
  exe <- .ieu_to_host(cfg$rscript %||% "C:/Program Files/R/R-4.2.2/bin/Rscript.exe")
  if (!file.exists(exe)) stop("找不到 Rscript: ", exe)
  message("easymr_ieu extract: ", exe, " ", .ieu_to_win(runner))
  status <- system2(exe, c("--vanilla", .ieu_to_win(runner)))
  ctx$results$easymr_ieu$exit_status <- status
  if (!identical(as.integer(status), 0L)) {
    warning("IEU 提取退出码 ", status)
  }
  ctx
}

if (exists("register_block", mode = "function")) {
  register_block("easymr_ieu", block_easymr_ieu, "查找并提取 OpenGWAS 欧洲人数据")
}
