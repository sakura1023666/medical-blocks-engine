charls_assign_followup <- function(year, month, calendar, died) {
  y <- suppressWarnings(as.integer(year))
  m <- suppressWarnings(as.integer(month))
  cal <- suppressWarnings(as.integer(calendar))
  cal[!cal %in% c(1L, 2L)] <- 1L
  died <- as.integer(died %in% TRUE | died == 1)
  key <- paste(y, m, cal, sep = "-")
  dt <- as.Date(unname(charls_ym_solar[key]))
  origin <- charls_followup_origin
  censor <- charls_followup_censor
  admin <- as.numeric(censor - origin) / 365.25
  time <- rep(admin, length(y))
  event <- died
  has <- !is.na(dt)
  early <- has & dt < origin & died == 1L
  late <- has & dt > censor & died == 1L
  ok <- has & died == 1L & dt >= origin & dt <= censor
  time[ok] <- as.numeric(dt[ok] - origin) / 365.25
  time[early] <- 15 / 365.25
  time[late] <- admin
  event[late] <- 0L
  miss <- died == 1L & !has
  time[miss] <- admin
  attr(time, "n_solar") <- sum(died == 1L & cal == 1L, na.rm = TRUE)
  attr(time, "n_lunar") <- sum(died == 1L & suppressWarnings(as.integer(calendar)) == 2L, na.rm = TRUE)
  attr(time, "n_early") <- sum(early)
  attr(time, "n_late") <- sum(late)
  attr(time, "n_date_missing") <- sum(miss)
  list(time = time, event = event)
}

